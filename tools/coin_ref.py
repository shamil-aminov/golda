# Golda's launcher coin, drawn the way the Lithuanian 50 € gold coin is: the facets and light from
# coin.py, then one gold hue, a wide lightness range, each facet a strong
# gradient (dark facets sinking to near black at the rim, lit ones flat cream), crisp seams,
# optionally a hairline of light on the folds that face the light.
import math, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = open(os.path.join(HERE, 'coin.py'), encoding='utf-8').read()
RES = os.path.join(HERE, '..', 'app', 'src', 'main', 'res', 'drawable')
REF = [(0.0, (0x24, 0x18, 0x00)), (0.15, (0x37, 0x26, 0x01)), (0.33, (0x8D, 0x63, 0x05)), (0.48, (0xB4, 0x8A, 0x2D)),
       (0.6, (0xC9, 0x9F, 0x42)), (0.76, (0xF3, 0xCB, 0x6F)), (0.9, (0xFF, 0xE7, 0xAD)), (1.0, (0xFF, 0xF4, 0xD8))]
def gold(t):
    t = max(0, min(1, t))
    for (t0, c0), (t1, c1) in zip(REF, REF[1:]):
        if t <= t1:
            k = (t - t0) / (t1 - t0)
            return '%02X%02X%02X' % tuple(round(c0[i] + (c1[i]-c0[i])*k) for i in range(3))

def build(name, spread=1.0, sink=0.32, lift=0.08, lines=0.0, base_shift=0.0, ladder=None):
    s = SRC[:SRC.index("fg, mono, svg = [], [], []")]
    g = {'__name__': 'v'}; exec(compile(s, 'coin', 'exec'), g)
    faces, shade, L, C, V = g['faces'], g['shade'], g['L'], g['C'], g['V']
    paths = []
    def P(f): return 'M' + ' L'.join(f'{p[0]:.2f},{p[1]:.2f}' for p in f) + ' Z'
    outline = P([(x, y, 0) for x, y in V])
    paths.append(f'    <path android:fillColor="#FF{gold(0.55)}" android:pathData="{outline}" />')
    order = sorted(range(len(faces)), key=lambda i: -shade(faces[i])[0])
    rank = {i: r for r, i in enumerate(order)}
    for fi, f in enumerate(faces):
        b, N = shade(f)
        b = 0.55 + (b - 0.55) * spread + base_shift
        if ladder: b = ladder[rank[fi]]
        inner = [p for p in f if p[2] > 0]; outer = [p for p in f if p[2] == 0]
        if inner and outer:
            ix, iy = sum(p[0] for p in inner)/len(inner), sum(p[1] for p in inner)/len(inner)
            ox, oy = sum(p[0] for p in outer)/len(outer), sum(p[1] for p in outer)/len(outer)
        else:
            cx, cy = sum(p[0] for p in f)/len(f), sum(p[1] for p in f)/len(f)
            ix, iy, ox, oy = cx + L[0]*10, cy + L[1]*10, cx - L[0]*10, cy - L[1]*10
        # Dark facets sink hard toward the rim; lit ones stay nearly flat cream.
        k = sink * (1 - min(1, max(0, (b - 0.45) / 0.4)))
        c_in, c_out = gold(b + lift), gold(b - k)
        paths.append(f'''    <path android:pathData="{P(f)}">
        <aapt:attr name="android:fillColor">
            <gradient android:type="linear" android:startX="{ix:.2f}" android:startY="{iy:.2f}" android:endX="{ox:.2f}" android:endY="{oy:.2f}" android:startColor="#FF{c_in}" android:endColor="#FF{c_out}" />
        </aapt:attr>
    </path>''')
    if lines > 0:
        key = lambda p: (round(p[0], 2), round(p[1], 2))
        edges = {}
        for i, f in enumerate(faces):
            for j in range(len(f)):
                a, b2 = f[j], f[(j+1) % len(f)]
                edges.setdefault(tuple(sorted([key(a), key(b2)])), []).append(i)
        for (a, b2), fs in edges.items():
            if len(fs) != 2: continue
            n = [x+y for x, y in zip(g['normal'](faces[fs[0]]), g['normal'](faces[fs[1]]))]
            m = math.sqrt(sum(x*x for x in n)); n = [x/m for x in n]
            lit = max(0, sum(n[i]*L[i] for i in range(3))) ** 3
            if lit < 0.2: continue
            dx, dy = b2[0]-a[0], b2[1]-a[1]; ln = math.hypot(dx, dy); nx, ny = -dy/ln*0.14, dx/ln*0.14
            pts = [(a[0]+nx, a[1]+ny), (b2[0]+nx, b2[1]+ny), (b2[0]-nx, b2[1]-ny), (a[0]-nx, a[1]-ny)]
            paths.append(f'    <path android:fillColor="#{int(255*lines*lit):02X}FFF4D8" android:pathData="{P(pts)}" />')
    head = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Golda's coin: faceted gold after the reference coin's gradients. Generated by coin_ref.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
'''
    open(os.path.join(RES, 'ic_launcher_foreground.xml'), 'w', encoding='utf-8', newline='\n').write(head + '\n'.join(paths) + '\n</vector>\n')

# Lightness by rank, brightest first, spread like the reference: mostly light and mid, two deep.
LAD_SOFT = [0.9, 0.85, 0.8, 0.75, 0.7, 0.65, 0.6, 0.55, 0.5, 0.4, 0.32]
build('coin', sink=0.2, lift=0.04, ladder=LAD_SOFT)
